"""Generate reversible Bash/Zsh activation for source-isolated package profiles."""
from __future__ import annotations

from pathlib import Path
import re
import shlex

from .storage import read_json


PATH_VARIABLES = {"PATH", "CMAKE_PREFIX_PATH", "PKG_CONFIG_PATH", "LD_LIBRARY_PATH", "LIBRARY_PATH", "CPATH",
                  "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH", "DYLD_LIBRARY_PATH", "DYLD_FALLBACK_LIBRARY_PATH"}


def activation(home, env_files, *, extra_variables=(), extra_paths=()):
    config = home.root / "config.json"
    base = Path(read_json(config).get("apt_base_home", str(home.root))) if config.exists() else home.root
    variables = set(PATH_VARIABLES) | set(extra_variables)
    paths = set(PATH_VARIABLES) | set(extra_paths)
    observed = set(env_files)
    observed.update(base.glob("packages/*/*/*/environment.sh"))
    observed.update(base.glob("apt/profiles/*/packages/*/*/*/environment.sh"))
    for path in observed:
        if path.is_file() and not path.is_symlink():
            for name, value in re.findall(r"(?m)^export ([A-Za-z_][A-Za-z0-9_]*)=(.*)$", path.read_text()):
                if name.startswith("_JFORGE_"):
                    continue
                variables.add(name)
                if "${" + name + ":+" in value:
                    paths.add(name)
    lines = ["#!/usr/bin/env bash", "# Generated by Jarvis-Forge; source in Bash or Zsh.",
             "if typeset -f _jforge_apt_restore >/dev/null 2>&1; then _jforge_apt_restore; fi"]
    lines.append(r'''_jforge_apt_filter() {
    local _jf_rest=$1 _jf_mode=$2 _jf_applied=${3-} _jf_before=${4-}
    local _jf_piece _jf_more _jf_drop _jf_out='' _jf_first=1
    local _jf_base=BASE_ROOT
    while :; do
        case "$_jf_rest" in
            *:*) _jf_piece=${_jf_rest%%:*}; _jf_rest=${_jf_rest#*:}; _jf_more=1 ;;
            *) _jf_piece=$_jf_rest; _jf_more=0 ;;
        esac
        _jf_drop=0
        if [ "$_jf_mode" = managed ]; then
            case "$_jf_piece" in
                "$_jf_base"/apps/*|"$_jf_base"/packages/*/prefix|"$_jf_base"/packages/*/prefix/*|"$_jf_base"/apt/profiles/*/packages/*/prefix|"$_jf_base"/apt/profiles/*/packages/*/prefix/*|"$_jf_base"/spack/store/*|"$_jf_base"/apt/profiles/*/spack/store/*) _jf_drop=1 ;;
            esac
        else
            case ":$_jf_applied:" in
                *":$_jf_piece:"*)
                    case ":$_jf_before:" in *":$_jf_piece:"*) ;; *) _jf_drop=1 ;; esac ;;
            esac
        fi
        if [ "$_jf_drop" = 0 ]; then
            if [ "$_jf_first" = 1 ]; then _jf_out=$_jf_piece; _jf_first=0
            else _jf_out=$_jf_out:$_jf_piece; fi
        fi
        [ "$_jf_more" = 1 ] || break
    done
    _JFORGE_APT_FILTERED=$_jf_out
}'''.replace("BASE_ROOT", shlex.quote(str(base))))
    for name in sorted(variables):
        if name in paths:
            lines += [f'if [ "${{{name}+x}}" = x ]; then',
                      f'  _jforge_apt_filter "${{{name}}}" managed',
                      f'  if [ -n "$_JFORGE_APT_FILTERED" ]; then export {name}="$_JFORGE_APT_FILTERED"; else unset {name}; fi',
                      'fi']
        else:
            literal = shlex.quote(str(base))
            lines += [f'case "${{{name}-}}" in *{literal}/apps/*|*{literal}/packages/*/prefix*|*{literal}/apt/profiles/*/packages/*/prefix*|*{literal}/spack/store/*|*{literal}/apt/profiles/*/spack/store/*) unset {name} ;; esac']
        lines += [f'_JFORGE_APT_HAD_{name}=${{{name}+x}}', f'_JFORGE_APT_OLD_{name}=${{{name}-}}']
    for path in env_files:
        lines.append("source " + shlex.quote(str(path)) + " || return $?")
    for name in sorted(variables):
        lines.append(f'_JFORGE_APT_NEW_{name}=${{{name}-}}')
    lines.append('_jforge_apt_restore() {')
    for name in sorted(variables):
        lines += [f'  if [ "${{{name}-}}" = "$_JFORGE_APT_NEW_{name}" ]; then',
                  f'    if [ "$_JFORGE_APT_HAD_{name}" = x ]; then export {name}="$_JFORGE_APT_OLD_{name}"; else unset {name}; fi']
        if name in paths:
            lines += ['  else', f'    _jforge_apt_filter "${{{name}-}}" additions "$_JFORGE_APT_NEW_{name}" "$_JFORGE_APT_OLD_{name}"',
                      f'    if [ -z "$_JFORGE_APT_FILTERED" ] && [ "$_JFORGE_APT_HAD_{name}" != x ]; then unset {name}; else export {name}="$_JFORGE_APT_FILTERED"; fi']
        lines += ['  fi', f'  unset _JFORGE_APT_HAD_{name} _JFORGE_APT_OLD_{name} _JFORGE_APT_NEW_{name}']
    lines += ['  unset _JFORGE_APT_FILTERED', '  unset -f _jforge_apt_restore _jforge_apt_filter', '}',
              'unset _JFORGE_APT_FILTERED', 'return 0']
    return "\n".join(lines) + "\n"
