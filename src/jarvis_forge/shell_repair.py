from .shell_activation import PATH_VARIABLES
from .storage import ForgeError, digest, new_id, read_json, write_json, write_text


WORKSPACE_HEADER = "# Generated by jforge; source this file in Bash.\n"
BUILD_HEADER = "# Generated by jforge build\n"
APT_HEADER = "# Generated by Jarvis-Forge; source in Bash or Zsh."
NAMED_HEADER = "# Managed by Jarvis-Forge; explicitly source this file to activate."
PATH_LISTS = PATH_VARIABLES | {"CMAKE_INCLUDE_PATH", "CMAKE_LIBRARY_PATH", "MANPATH", "INFOPATH", "PYTHONPATH"}
DIRECTORIES = {"ROOTSYS", "ROOT_DIR", "EIGEN3_ROOT", "EIGEN3_INCLUDE_DIR", "Eigen3_DIR"}
EXECUTABLES = {"CC", "CXX", "FC"}
PYTHON_SELECTION = {"PYENV_ROOT", "PYENV_VERSION", "PYTHONHOME", "VIRTUAL_ENV", "CONDA_PREFIX"}

_EXPANSION = r"\$\{(?:[^{}\n]|\$\{[A-Za-z_][A-Za-z_0-9]*\})*\}|\$[A-Za-z_][A-Za-z_0-9]*"
_TOKEN = re.compile(
    rf"""'(?P<single>[^'\n]*)'|"(?P<double>(?:[^"\\\n]|\\[^\n])*)"|"""
    rf"""\\(?P<escaped>[^\n])|(?P<expansion>{_EXPANSION})|(?P<literal>[a-zA-Z0-9_./:+,%@=-])"""
)
_DOUBLE = re.compile(rf"""\\(?P<escaped>["\\$`])|(?P<expansion>{_EXPANSION})|(?P<literal>[^"$`\\]+|\\)""")
_WORD = rf"(?:{_TOKEN.pattern})+"
_TAIL = r"(?P<tail>[ \t]+(?:#.*)?)?"
_SOURCE = re.compile(rf"[ \t]*(?:source|\.)[ \t]+(?P<word>{_WORD})(?P<guard>[ \t]+\|\|[ \t]+return[ \t]+\$\?)?{_TAIL}")
_ASSIGN = re.compile(rf"[ \t]*(?:export[ \t]+)?(?P<name>[A-Za-z_][A-Za-z0-9_]*)=(?P<word>{_WORD}){_TAIL}")


def _word_parts(word):
    """Decode literal quoting and record expansions separately."""
    parts = []
    for token in _TOKEN.finditer(word):
        if token["double"] is not None:
            body = token["double"]
            offset = 0
            for piece in _DOUBLE.finditer(body):
                if piece.start() != offset:
                    return None
                parts.append((piece["expansion"] is not None, piece["expansion"] or piece["escaped"] or piece["literal"]))
                offset = piece.end()
            if offset != len(body):
                return None
        else:
            parts.append((token["expansion"] is not None, token["expansion"] or token["escaped"]
                          or token["literal"] or token["single"] or ""))
    return parts


def _path_status(value, kind):
    path = Path(value)
    if not path.is_absolute():
        return "unchecked", "depends on the caller's working directory" if value else "empty search component"
    try:
        mode = path.stat().st_mode
    except (FileNotFoundError, NotADirectoryError):
        return "invalid", "missing target or dangling link"
    except OSError as exc:
        if exc.errno == errno.ELOOP:
            return "invalid", "symbolic link loop"
        return "unchecked", exc.strerror or "cannot check target"
    if kind == "directory" and not stat.S_ISDIR(mode):
        return "invalid", "expected a directory"
    if kind in {"source", "executable"} and not stat.S_ISREG(mode):
        return "invalid", "expected a regular file"
    if kind == "source" and not os.access(path, os.R_OK):
        return "unchecked", "target cannot be read"
    if kind == "executable" and not os.access(path, os.X_OK):
        return "invalid", "target is not executable"
    return "kept", "target exists"


def _variable_kind(name):
    if name in EXECUTABLES:
        return "executable"
    if name in DIRECTORIES or (name in PATH_LISTS and name != "PYTHONPATH"):
        return "directory"
    return "path"


class Repair:
    """Plan checked changes, then publish any needed runtime copies and a receipt."""

    def __init__(self, path, directory, dry_run):
        self.path = path
        self.directory = directory
        self.dry_run = dry_run
        self.items = []
        self.originals = {}
        self.copies = {}
        self.bash = shutil.which("bash")
        if not self.bash:
            raise ForgeError("Bash is required to check activation script syntax.")
        self.bash_env = {key: value for key, value in os.environ.items() if key not in
                         {"BASH_ENV", "ENV", "BASHOPTS", "SHELLOPTS"} and not key.startswith("BASH_FUNC_")}

    def _syntax(self, text):
        check = subprocess.run([self.bash, "--noprofile", "--norc", "-n"], input=text,
                               stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True,
                               env=self.bash_env, timeout=10)
        return check.stderr.strip() or ("Bash syntax check failed." if check.returncode else "")

    def _check(self, path, text):
        problem = self._syntax(text)
        if problem:
            raise ForgeError(f"Invalid Bash activation script {path}:\n{problem}")

    def _commands(self, text):
        # Bash identifies statement boundaries, including here-docs and compound
        # commands. Only independent single-line statements can be edited.
        pending = ""
        for number, line in enumerate(StringIO(text), 1):
            if not pending:
                start = number
                if not line.strip(" \t\n") or line.lstrip(" \t").startswith("#"):
                    yield start, line
                    continue
            pending += line
            if line.endswith("\\\n") or self._syntax(pending):
                continue
            # Bash 3.2 accepts EOF inside a here-doc without a warning. An
            # unmatched closing parenthesis is then consumed as data.
            if "<<" in pending and not self._syntax(pending + "\n)\n"):
                continue
            yield start, pending
            pending = ""
        if pending:
            yield start, pending

    def _record(self, path, number, kind, status, reason, *, name=None, value=None, entry=False):
        item = {"script": str(path), "entry" if entry else "line": number,
                "kind": kind, "status": status, "reason": reason}
        if name is not None:
            item["name"] = name
        if value is not None:
            item["value"] = value
        self.items.append(item)

    def _setting(self, path, number, match, parts):
        name = match["name"]
        if name not in PATH_LISTS | DIRECTORIES | EXECUTABLES:
            self._record(path, number, "variable", "unchecked", "no filesystem check defined", name=name)
            return match[0]
        kind = _variable_kind(name)
        inherited = [value for expanded, value in parts or () if expanded]
        value = "".join("\0" if expanded else piece for expanded, piece in parts or ())
        prefix, suffix = "", ""
        if name in PATH_LISTS and len(inherited) == 1:
            for reference in (f"${name}", f"${{{name}}}"):
                if value.endswith("\0") and inherited[0] == f"${{{name}:+:{reference}}}":
                    suffix = '"' + inherited.pop() + '"'
                    value = value[:-1]
                    break
                if value.startswith("\0") and inherited[0] == f"${{{name}:+{reference}:}}":
                    prefix = '"' + inherited.pop() + '"'
                    value = value[1:]
                    break
        values = value.split(":") if name in PATH_LISTS else [value]
        if parts is None or (inherited and
                (name not in PATH_LISTS or inherited not in ([f"${name}"], [f"${{{name}}}"]) or "\0" not in values)):
            self._record(path, number, "variable", "unchecked", "dynamic path expression", name=name)
            return match[0]
        kept = []
        for component in values:
            if component == "\0":
                self._record(path, number, kind, "unchecked", "inherited from the calling shell",
                             name=name, value=inherited[0])
                kept.append('"' + inherited[0] + '"')
                continue
            status, reason = _path_status(component, kind)
            self._record(path, number, kind, "removed" if status == "invalid" else status, reason,
                         name=name, value=component)
            if status != "invalid":
                kept.append(shlex.quote(component))
        if prefix or suffix:
            self._record(path, number, kind, "unchecked", "inherited from the calling shell",
                         name=name, value=(prefix or suffix)[1:-1])
        if len(kept) == len(values):
            return match[0]
        return self._replace(match, prefix + ":".join(kept) + suffix if kept else None)

    @staticmethod
    def _replace(match, word):
        if word is None:
            return (match["tail"] or "").lstrip()  # Preserve an inline comment.
        start, end = match.span("word")
        return match[0][:start] + word + match[0][end:]

    def _source(self, path, number, match, parts, ancestors):
        if parts is None or any(expanded for expanded, _ in parts):
            self._record(path, number, "source", "unchecked", "dynamic source target")
            return match[0]
        value = "".join(piece for _, piece in parts)
        status, reason = _path_status(value, "source")
        dependency = Path(value)
        if status == "kept" and dependency.resolve() in ancestors:
            status, reason = "invalid", "cyclic source reference"
        self._record(path, number, "source", "removed" if status == "invalid" else status, reason, value=value)
        if status == "invalid":
            return self._replace(match, None)
        if status != "kept":
            return match[0]
        with dependency.open("rb") as stream:
            header = stream.readline(128)
        replacement = value
        if header in {BUILD_HEADER.encode(), WORKSPACE_HEADER.encode()}:
            if dependency not in self.copies:
                content = self.scan(dependency, ancestors)
                if content != self.originals[dependency]:
                    target = self.directory / f"source-{len(self.copies) + 1}.sh"
                    self.copies[dependency] = (target, content)
                else:
                    self.copies[dependency] = (dependency, None)
            replacement = str(self.copies[dependency][0])
        else:
            self._record(dependency, 1, "script", "unchecked", "external script body")
        rewritten = match[0] if replacement == value else self._replace(match, shlex.quote(replacement))
        if self.originals[path].startswith((WORKSPACE_HEADER, BUILD_HEADER)) and not match["guard"]:
            tail = match["tail"] or ""
            rewritten = rewritten.removesuffix(tail) if tail else rewritten
            rewritten += " || return $?" + tail
        return rewritten

    def scan(self, path, ancestors=frozenset()):
        try:
            original = path.read_bytes().decode("utf-8")
        except UnicodeError as exc:
            raise ForgeError(f"Activation script is not UTF-8: {path}") from exc
        if "\0" in original:
            raise ForgeError(f"Activation script contains a NUL byte: {path}")
        self._check(path, original)
        self.originals[path] = original
        ancestors = ancestors | {path.resolve()}
        legacy = original.startswith(BUILD_HEADER + "set -e\nset -o pipefail\n")
        from .cmake import CHILD_ENVIRONMENT_FILES

        lines = []
        for number, command in self._commands(original):
            statement = command.rstrip("\n")
            if not statement.strip(" \t") or statement.lstrip(" \t").startswith("#"):
                lines.append(command)
                continue
            source = _SOURCE.fullmatch(statement)
            setting = _ASSIGN.fullmatch(statement)
            if legacy and (number in {2, 3} or (path.name in CHILD_ENVIRONMENT_FILES and not source)):
                self._record(path, number, "shell", "removed", "legacy build-only setting")
                continue
            if source:
                fixed = self._source(path, number, source, _word_parts(source["word"]), ancestors)
            elif setting:
                fixed = self._setting(path, number, setting, _word_parts(setting["word"]))
            else:
                self._record(path, number, "shell", "unchecked", "compound or unsupported shell statement")
                fixed = statement
            if fixed:
                lines.append(fixed + command[len(statement):])
        content = "".join(lines)
        if content != original:
            self._check(path, content)
        return content

    def report(self, *, changed, **extra):
        return {"schema_version": 1, "activation": str(self.path), "dry_run": self.dry_run, "changed": changed,
                "removed": sum(item["status"] == "removed" for item in self.items),
                "unchecked": sum(item["status"] == "unchecked" for item in self.items),
                "settings": self.items, **extra}

    def save(self, report):
        for path, original in self.originals.items():
            if path.read_bytes() != original.encode("utf-8"):
                raise ForgeError(f"Activation script changed during repair: {path}", code=1)
        if self.directory.parent.is_symlink():
            raise ForgeError(f"Repair directory must not be a symbolic link: {self.directory.parent}")
        self.directory.mkdir(parents=True, mode=0o700)
        for target, content in self.copies.values():
            if content is not None:
                write_text(target, content)
        if report["changed"]:
            backup = self.directory / "original.sh"
            write_text(backup, self.originals[self.path])
            report["backup"] = str(backup)
        report["report"] = str(self.directory / "report.json")
        write_json(self.directory / "report.json", report)


@contextmanager
def activation_lock(path):
    # Build publication and repair serialize updates to the same workspace entry.
    metadata = path.parent / ".jforge"
    workspace = path.name == "activate.sh" and (metadata / "workspace.json").is_file()
    if workspace and metadata.is_symlink():
        raise ForgeError(f"Workspace metadata must not be a symbolic link: {metadata}")
    lock = metadata / "activation.lock" if workspace else path.with_name(f".{path.name}.jforge-lock")
    with os.fdopen(os.open(lock, os.O_WRONLY | os.O_CREAT | os.O_NOFOLLOW, 0o600), "a") as stream:
        try:
            fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise ForgeError(f"Another activation update is in progress: {path}", code=1) from exc
        yield


def repair_file(path, *, dry_run=False):
    path = path.expanduser()
    if path.is_symlink() or not path.is_file():
        raise ForgeError(f"Expected a regular activation script: {path}")
    path = path.resolve()
    directory = path.parent / f".{path.name}.jforge-repairs" / new_id("repair")

    def verify_target():
        with path.open("rb") as stream:
            headers = {stream.readline(128).rstrip(b"\r\n") for _ in range(2)}
        if (headers & {BUILD_HEADER.rstrip().encode(), NAMED_HEADER.encode(), APT_HEADER.encode()} or
                (path.parent / "manifest.json").is_file() and path.name in {"activate.sh", "source.sh"}):
            raise ForgeError(f"Activation is part of a published record: {path}",
                             hint="Select an environment name, apt, or the workspace activate.sh.")

    def inspect():
        verify_target()
        repair = Repair(path, directory, dry_run)
        content = repair.scan(path)
        report = repair.report(changed=content != repair.originals[path])
        if not dry_run:
            repair.save(report)
            if report["changed"]:
                write_text(path, content, mode=stat.S_IMODE(path.stat().st_mode))
        return report

    if dry_run:
        return inspect()
    verify_target()
    with activation_lock(path):
        if path.is_symlink():
            raise ForgeError(f"Expected a regular activation script: {path}")
        return inspect()


def repair_apt(home, *, dry_run=False):
    from .apt_profiles import active_home
    from .package_operations import _inside, locked
    from .spack_backend import repaired_runtime_environment

    home = active_home(home)
    state_path = _inside(home, home.root / "apt/state.json")

    def inspect():
        state = read_json(state_path)
        if not state.get("spack") or not state.get("activation"):
            raise ForgeError("No Spack package environment has been published.")
        original = _inside(home, Path(state["activation"]))
        revision = original.parent
        operation_id = new_id("repair")
        directory = _inside(home, revision / "repairs" / operation_id)
        if state.get("activation_repair"):
            current, modifications = repaired_runtime_environment(home, state, materialize=False)
        else:
            current, modifications = original, _inside(home, revision / "modifications.json")
        rows = _spack_rows(modifications)
        operation = Repair(current, directory, dry_run)
        repaired = []
        for index, row in enumerate(rows, 1):
            name, action, value = row["name"], row["type"], row.get("value")
            path_list = action in {"SetPath", "PrependPath", "AppendPath"} or (
                action == "SetEnv" and name in PATH_LISTS)
            scalar = action == "SetEnv" and name in DIRECTORIES | EXECUTABLES
            if (not path_list and not scalar) or name in PYTHON_SELECTION or row.get("raw"):
                operation._record(modifications, index, action, "unchecked", "no filesystem check defined",
                                  name=name, entry=True)
                repaired.append(row)
                continue
            separator = row.get("separator", os.pathsep)
            values = value.split(separator) if path_list else [value]
            kept = []
            for entry in values:
                if any(character in entry for character in "$*?["):
                    status, reason = "unchecked", "dynamic or template path"
                else:
                    status, reason = _path_status(entry, _variable_kind(name))
                operation._record(modifications, index, action, "removed" if status == "invalid" else status,
                                  reason, name=name, value=entry, entry=True)
                if status != "invalid":
                    kept.append(entry)
            if kept:
                repaired.append({**row, "value": separator.join(kept)})
        report = operation.report(changed=rows != repaired, name="apt")
        if not dry_run:
            directory.mkdir(parents=True, mode=0o700)
            report["report"] = str(directory / "report.json")
            selected = None
            if report["changed"]:
                updated = directory / "modifications.json"
                write_text(updated, json.dumps(repaired, indent=2) + "\n")
                selected = {**state, "activation_repair": {"id": operation_id, "sha256": digest(updated)}}
                activation, _ = repaired_runtime_environment(home, selected)
                report["activation"] = str(activation)
            write_json(directory / "report.json", report)
            if selected:
                write_json(state_path, selected)
        return report

    if not state_path.is_file():
        raise ForgeError("No Spack package environment has been published.")
    if dry_run:
        return inspect()
    with locked(home):
        return inspect()


def _spack_rows(path):
    try:
        rows = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ForgeError(f"Cannot read Spack activation settings: {path}") from exc
    if not isinstance(rows, list) or any(
            not isinstance(row, dict) or not isinstance(row.get("name"), str)
            or not isinstance(row.get("type"), str)
            or (row["type"] in {"SetPath", "PrependPath", "AppendPath", "SetEnv"}
                and not isinstance(row.get("value"), str))
            or ("separator" in row and not (isinstance(row["separator"], str) and row["separator"]))
            for row in rows):
        raise ForgeError(f"Invalid Spack activation settings: {path}")
    return rows
