"""CMake command planning and environment materialization for project builds."""

from __future__ import annotations

import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess

from .storage import ForgeError, digest, write_text

CHILD_ENVIRONMENT_FILES = {"environment.sh", "runtime-environment.sh"}


def commands(options, source, build, prefix, *, jobs=1):
    """Return literal argv, including native presets and typed cache entries."""
    cmake = options.get("executable", "cmake")
    configure = [cmake, "-S", str(source), "-B", str(build)]
    if options.get("configure_preset"):
        configure += ["--preset", options["configure_preset"]]
    if options.get("generator"):
        configure += ["-G", options["generator"]]
    if options.get("toolchain_file"):
        configure += ["--toolchain", options["toolchain_file"]]
    configure += [f"-DCMAKE_INSTALL_PREFIX:PATH={prefix}"]
    for key, entry in options.get("cache", {}).items():
        value = entry["value"]
        if isinstance(value, bool):
            value = "ON" if value else "OFF"
        elif isinstance(value, list):
            value = ";".join(str(v).replace(";", r"\;") for v in value)
        configure += [f"-D{key}:{entry['type']}={value}"]
    compile_ = [cmake, "--build", str(build)]
    if options.get("build_preset"):
        compile_ += ["--preset", options["build_preset"]]
    compile_ += ["--parallel", str(jobs)]
    if options.get("targets"):
        compile_ += ["--target", *options["targets"]]
    install = [cmake, "--install", str(build)]
    if options.get("component"):
        install += ["--component", options["component"]]
    test = ["ctest", "--test-dir", str(build), "--output-on-failure", "--parallel", str(jobs)]
    if options.get("test_preset"):
        test += ["--preset", options["test_preset"]]
    for argv in (compile_, install, test):
        if options.get("configuration"):
            argv += ["-C" if argv[0] == "ctest" else "--config", options["configuration"]]
    return {"configure": configure, "build": compile_, "install": install, "test": test}


def write_environment(path, *, base=None, scripts=(), variables=None, paths=None):
    """Create an explicit child environment; no parent-shell state is changed."""
    lines = ["# Generated by jforge build"]
    if base is not None:
        lines += ["set -e", "set -o pipefail"]
        # Unset ambient variables: a resumed job must not inherit a changed shell.
        for key in ("CPATH", "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH", "LIBRARY_PATH",
                    "LD_LIBRARY_PATH", "CMAKE_PREFIX_PATH", "CMAKE_INCLUDE_PATH", "CMAKE_LIBRARY_PATH", "PKG_CONFIG_PATH", "ROOTSYS",
                    "CC", "CXX", "FC", "PYTHONPATH"):
            if key not in base:
                lines.append(f"unset {key}")
        for key, value in sorted(base.items()):
            if key in {"_", "SHLVL", "PWD", "OLDPWD", "BASHOPTS", "SHELLOPTS"} or key.startswith("BASH_FUNC_"):
                continue
            if key.isidentifier():
                lines.append(f"export {key}={shlex.quote(value)}")
    def prepend_paths():
        for key, values in (paths or {}).items():
            values = list(dict.fromkeys(str(v) for v in values if v))
            if values:
                joined = shlex.quote(os.pathsep.join(values))
                lines.append(f'export {key}={joined}${{{key}:+:${key}}}')
    # Runtime dependencies must already be available to commands inside activation.
    prepend_paths()
    for script in scripts:
        failure = " || return $?" if base is None else ""
        lines.append("source " + shlex.quote(str(script)) + failure)
    if scripts:
        prepend_paths()
    for key, value in (variables or {}).items():
        lines.append(f"export {key}={shlex.quote(str(value))}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    path.chmod(0o600)
    return path


def runtime_activation(path, ancestors=frozenset()):
    """Export a safe entry point for a legacy Forge-generated runtime script."""
    if path.name == "spack-environment.sh":
        from .spack_backend import refresh_runtime_adapter
        return refresh_runtime_adapter(path)
    legacy = "# Generated by jforge build\nset -e\nset -o pipefail\n"
    header = "# Generated by jforge build\n"
    text = path.read_text()
    if not text.startswith(header):
        return path
    resolved = path.resolve()
    if resolved in ancestors:
        raise ForgeError(f"Cyclic runtime activation: {path}")
    body = text.removeprefix(legacy) if text.startswith(legacy) else text.removeprefix(header)
    captured_child = path.name in CHILD_ENVIRONMENT_FILES and text.startswith(legacy)
    lines = [header]
    line = ""
    for part in body.splitlines(keepends=True):
        line += part
        try:
            argv = shlex.split(line)
        except ValueError:
            continue
        if argv[:1] == ["source"]:
            if len(argv) != 2 and argv[2:] != ["||", "return", "$?"]:
                raise ForgeError(f"Unsupported generated activation source command: {path}")
            dependency = Path(argv[1])
            if dependency.is_file():
                dependency = runtime_activation(dependency, ancestors | {resolved})
            line = "source " + shlex.quote(str(dependency)) + " || return $?\n"
        if not captured_child or argv[:1] == ["source"]:
            lines.append(line)
        line = ""
    if line:
        raise ForgeError(f"Incomplete generated activation command: {path}")
    content = "".join(lines)
    if content == text:
        return path
    destination = path.with_name(path.stem + ".runtime.sh")
    if destination.is_file() and destination.read_text() == content:
        return destination
    write_text(destination, content)
    return destination


def capture(script=None):
    """Capture only exported environment, keeping shell chatter out of the data."""
    import sys
    code = "import os,json; print('JFORGE_ENV_JSON='+json.dumps(dict(os.environ)))"
    prefix = "set -e; " + ("source " + shlex.quote(str(script)) + "; " if script else "")
    result = subprocess.run(["bash", "--noprofile", "--norc", "-c",
                             prefix + 'exec "$@"', "jforge-env", sys.executable, "-I", "-c", code],
                            stdin=subprocess.DEVNULL, capture_output=True, timeout=60)
    if result.returncode:
        raise ForgeError("Environment activation failed: " + result.stderr.decode(errors="replace"), code=1)
    for line in reversed(result.stdout.decode(errors="replace").splitlines()):
        if line.startswith("JFORGE_ENV_JSON="):
            return json.loads(line.split("=", 1)[1])
    raise ForgeError("Environment activation did not produce an environment record.", code=1)


def tools(environment):
    result = {}
    for key, fallback in (("CC", "cc"), ("CXX", "c++"), ("FC", "gfortran"), ("python", "python3"),
                          ("cmake", "cmake"), ("ctest", "ctest"), ("pkg-config", "pkg-config")):
        requested = environment.get(key, fallback) if key != "python" else fallback
        if len(shlex.split(requested)) != 1:
            raise ForgeError(f"Select a single compiler executable for {key}: {requested}")
        executable = shutil.which(requested, path=environment.get("PATH"))
        if executable:
            argv = [executable, "-c", "import sys,sysconfig,json; print(json.dumps({'path':sys.executable,'version':sys.version,'abi':sysconfig.get_config_var('SOABI')}))"] if key == "python" else [executable, "--version"]
            probe = subprocess.run(argv, env=environment, capture_output=True, timeout=30)
            if probe.returncode:
                raise ForgeError(f"Cannot inspect selected {key}: {executable}", code=1)
            observed = probe.stdout.decode(errors="replace").strip()
            result[key] = json.loads(observed) if key == "python" else {
                "path": str(Path(executable).absolute()), "version": observed}
    return result


def cache_values(build):
    cache = build / "CMakeCache.txt"
    values = {}
    if cache.is_file():
        for line in cache.read_text(errors="replace").splitlines():
            if line and not line.startswith(("//", "#")) and ":" in line and "=" in line:
                left, value = line.split("=", 1)
                values[left.split(":", 1)[0]] = value
    return values


def manifest(prefix):
    """A verified installation manifest, including symlink identity and targets."""
    records = {}
    for path in sorted(prefix.rglob("*")):
        if path.is_symlink():
            records[str(path.relative_to(prefix))] = {"link": os.readlink(path)}
        elif path.is_file():
            records[str(path.relative_to(prefix))] = {"sha256": digest(path)}
    if not records:
        raise ForgeError(f"Installation has no files: {prefix}", code=1)
    return records


def verify_manifest(prefix, records):
    for name, expected in records.items():
        path = prefix / name
        if Path(name).is_absolute() or ".." in Path(name).parts:
            raise ForgeError("Invalid installation manifest path.")
        good = (path.is_symlink() and os.readlink(path) == expected["link"]) if "link" in expected else (
            path.is_file() and not path.is_symlink() and digest(path) == expected["sha256"])
        if not good:
            raise ForgeError(f"Installed artifact is missing or modified: {path}", code=1)
