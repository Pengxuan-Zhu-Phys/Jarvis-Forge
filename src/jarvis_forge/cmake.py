import re
import shlex
import shutil
import subprocess
import sys

from .storage import ForgeError, digest, write_text

CHILD_ENVIRONMENT_FILES = {"environment.sh", "runtime-environment.sh"}


def commands(options, source, build, prefix, *, jobs=1):
    """Return literal argv, including native presets and typed cache entries."""
    cmake = options.get("executable", "cmake")
    # A preset owns its binary directory. Passing -B would override ${sourceDir}/build.
    configure = [cmake, "-S", str(source)]
    if options.get("binary_dir") != "preset":
        configure += ["-B", str(build)]
    if options.get("configure_preset"):
        configure += ["--preset", options["configure_preset"]]
    if options.get("generator"):
        configure += ["-G", options["generator"]]
    if options.get("toolchain_file"):
        configure += ["--toolchain", options["toolchain_file"]]
    if not options.get("in_place"):
        configure += [f"-DCMAKE_INSTALL_PREFIX:PATH={prefix}"]
    for key, entry in options.get("cache", {}).items():
        value = entry["value"]
        if isinstance(value, bool):
            value = "ON" if value else "OFF"
        elif isinstance(value, list):
            value = ";".join(str(v).replace(";", r"\;") for v in value)
        configure += [f"-D{key}:{entry['type']}={value}"]
    compile_ = [cmake, "--build", str(build)]
    if options.get("build_preset"):
        compile_ += ["--preset", options["build_preset"]]
    compile_ += ["--parallel", str(jobs)]
    if options.get("targets"):
        compile_ += ["--target", *options["targets"]]
    install = [cmake, "--install", str(build)]
    if options.get("component"):
        install += ["--component", options["component"]]
    test = ["ctest", "--test-dir", str(build), "--output-on-failure", "--parallel", str(jobs)]
    if options.get("test_preset"):
        test += ["--preset", options["test_preset"]]
    for argv in (compile_, install, test):
        if options.get("configuration"):
            argv += ["-C" if argv[0] == "ctest" else "--config", options["configuration"]]
    return {"configure": configure, "build": compile_, "install": install, "test": test}


def write_environment(path, *, base=None, scripts=(), variables=None, paths=None, profile_instance=None, build_id=None):
    """Create an explicit child environment; no parent-shell state is changed."""
    lines = ["# Generated by jforge build"]
    if profile_instance:
        name = shlex.quote(profile_instance)
        message = shlex.quote(f"This build requires profile {profile_instance}.")
        lines += [f'if [ "${{JFORGE_PROFILE_INSTANCE-}}" != {name} ]; then',
                  f"  printf '%s\\n' {message} >&2", "  return 1", "fi"]
    if base is not None:
        lines += ["set -e", "set -o pipefail"]
        # Unset ambient variables: a resumed job must not inherit a changed shell.
        for key in ("CPATH", "C_INCLUDE_PATH", "CPLUS_INCLUDE_PATH", "LIBRARY_PATH",
                    "LD_LIBRARY_PATH", "CMAKE_PREFIX_PATH", "CMAKE_INCLUDE_PATH", "CMAKE_LIBRARY_PATH", "PKG_CONFIG_PATH", "ROOTSYS",
                    "CC", "CXX", "FC", "PYTHONPATH"):
            if key not in base:
                lines.append(f"unset {key}")
        for key, value in sorted(base.items()):
            if key in {"_", "SHLVL", "PWD", "OLDPWD", "BASHOPTS", "SHELLOPTS"} or key.startswith("BASH_FUNC_"):
                continue
            if key.isidentifier():
                lines.append(f"export {key}={shlex.quote(value)}")
    def prepend_paths():
        for key, values in (paths or {}).items():
            values = list(dict.fromkeys(str(v) for v in values if v))
            if values:
                joined = shlex.quote(os.pathsep.join(values))
                lines.append(f'export {key}={joined}${{{key}:+:${key}}}')
    # Runtime dependencies must already be available to commands inside activation.
    prepend_paths()
    for script in scripts:
        failure = " || return $?" if base is None else ""
        lines.append("source " + shlex.quote(str(script)) + failure)
    if scripts:
        prepend_paths()
    for key, value in (variables or {}).items():
        lines.append(f"export {key}={shlex.quote(str(value))}")
    if build_id:
        lines.append('export JFORGE_ACTIVE_OUTPUTS="${JFORGE_ACTIVE_OUTPUTS:+$JFORGE_ACTIVE_OUTPUTS:}"' + shlex.quote(build_id))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    path.chmod(0o600)
    return path


def runtime_activation(path, ancestors=frozenset()):
    """Export a safe entry point for a legacy Forge-generated runtime script."""
    if path.name == "spack-environment.sh":
        from .spack_backend import refresh_runtime_adapter
        return refresh_runtime_adapter(path)
    legacy = "# Generated by jforge build\nset -e\nset -o pipefail\n"
    header = "# Generated by jforge build\n"
    text = path.read_text()
    if not text.startswith(header):
        return path
    resolved = path.resolve()
    if resolved in ancestors:
        raise ForgeError(f"Cyclic runtime activation: {path}")
    body = text.removeprefix(legacy) if text.startswith(legacy) else text.removeprefix(header)
    captured_child = path.name in CHILD_ENVIRONMENT_FILES and text.startswith(legacy)
    lines = [header]
    line = ""
    for part in body.splitlines(keepends=True):
        line += part
        try:
            argv = shlex.split(line)
        except ValueError:
            continue
        if argv[:1] == ["source"]:
            if len(argv) != 2 and argv[2:] != ["||", "return", "$?"]:
                raise ForgeError(f"Unsupported generated activation source command: {path}")
            dependency = Path(argv[1])
            if dependency.is_file():
                dependency = runtime_activation(dependency, ancestors | {resolved})
            line = "source " + shlex.quote(str(dependency)) + " || return $?\n"
        if not captured_child or argv[:1] == ["source"]:
            lines.append(line)
        line = ""
    if line:
        raise ForgeError(f"Incomplete generated activation command: {path}")
    content = "".join(lines)
    if content == text:
        return path
    destination = path.with_name(path.stem + ".runtime.sh")
    if destination.is_file() and destination.read_text() == content:
        return destination
    write_text(destination, content)
    return destination


def capture(script=None, *, environment=None, cwd=None):
    """Capture only exported environment, keeping shell chatter out of the data."""
    import sys
    code = "import os,json; print('JFORGE_ENV_JSON='+json.dumps(dict(os.environ)))"
    prefix = "set -e; " + ("source " + shlex.quote(str(script)) + "; " if script else "")
    bash = shutil.which("bash") or "bash"
    result = subprocess.run([bash, "--noprofile", "--norc", "-c",
                             prefix + 'exec "$@"', "jforge-env", sys.executable, "-I", "-c", code],
                            stdin=subprocess.DEVNULL, capture_output=True, timeout=60, env=environment, cwd=cwd)
    if result.returncode:
        raise ForgeError("Environment activation failed: " + result.stderr.decode(errors="replace"), code=1)
    for line in reversed(result.stdout.decode(errors="replace").splitlines()):
        if line.startswith("JFORGE_ENV_JSON="):
            return json.loads(line.split("=", 1)[1])
    raise ForgeError("Environment activation did not produce an environment record.", code=1)


def tools(environment):
    result = {}
    for key, fallback in (("CC", "cc"), ("CXX", "c++"), ("FC", "gfortran"), ("python", "python3"),
                          ("cmake", "cmake"), ("ctest", "ctest"), ("pkg-config", "pkg-config")):
        requested = environment.get(key, fallback) if key != "python" else fallback
        if len(shlex.split(requested)) != 1:
            raise ForgeError(f"Select a single compiler executable for {key}: {requested}")
        executable = shutil.which(requested, path=environment.get("PATH"))
        if executable:
            argv = [executable, "-c", "import sys,sysconfig,json; print(json.dumps({'path':sys.executable,'version':sys.version,'abi':sysconfig.get_config_var('SOABI')}))"] if key == "python" else [executable, "--version"]
            probe = subprocess.run(argv, env=environment, capture_output=True, timeout=30)
            if probe.returncode:
                raise ForgeError(f"Cannot inspect selected {key}: {executable}", code=1)
            observed = probe.stdout.decode(errors="replace").strip()
            result[key] = json.loads(observed) if key == "python" else {
                "path": str(Path(executable).absolute()), "version": observed}
    return result


def cache_values(build):
    cache = build / "CMakeCache.txt"
    values = {}
    if cache.is_file():
        for line in cache.read_text(errors="replace").splitlines():
            if line and not line.startswith(("//", "#")) and ":" in line and "=" in line:
                left, value = line.split("=", 1)
                values[left.split(":", 1)[0]] = value
    return values


def manifest(prefix):
    """A verified installation manifest, including symlink identity and targets."""
    records = {}
    for path in sorted(prefix.rglob("*")):
        if path.is_symlink():
            records[str(path.relative_to(prefix))] = {"link": os.readlink(path)}
        elif path.is_file():
            records[str(path.relative_to(prefix))] = {"sha256": digest(path)}
    if not records:
        raise ForgeError(f"Installation has no files: {prefix}", code=1)
    return records


def verify_manifest(prefix, records):
    for name, expected in records.items():
        path = prefix / name
        if Path(name).is_absolute() or ".." in Path(name).parts:
            raise ForgeError("Invalid installation manifest path.")
        good = (path.is_symlink() and os.readlink(path) == expected["link"]) if "link" in expected else (
            path.is_file() and not path.is_symlink() and digest(path) == expected["sha256"])
        if not good:
            raise ForgeError(f"Installed artifact is missing or modified: {path}", code=1)


_PRESET_MACRO = re.compile(
    r"\$\{([A-Za-z0-9_]+)\}|\$env\{([A-Za-z_][A-Za-z0-9_]*)\}|\$penv\{([A-Za-z_][A-Za-z0-9_]*)\}")


def preset_binary_dir(source, name):
    """Resolve one configure preset's binaryDir, including hidden parents."""
    source = Path(source).resolve()
    presets = _configure_presets(source)
    if name not in presets:
        known = ", ".join(sorted(presets)) or "none"
        raise ForgeError(f"CMake configure preset not found: {name}. Known presets: {known}.")
    resolved = _resolve_preset(presets, name, [])
    binary = resolved.get("binaryDir")
    if not isinstance(binary, str) or not binary:
        raise ForgeError(f"CMake preset {name} has no binaryDir.")
    expanded = _expand_preset_path(binary, source=source, preset=name,
                                   file_dir=Path(resolved.get("_file_dir", source)),
                                   generator=resolved.get("generator") or "")
    path = Path(expanded)
    if not path.is_absolute():
        path = source / path
    return path.resolve()


def _configure_presets(source):
    collected = {}
    for filename in ("CMakePresets.json", "CMakeUserPresets.json"):
        path = source / filename
        if path.is_file():
            _load_presets(path, collected, set())
    if not collected:
        raise ForgeError(f"No CMake configure presets in {source}.")
    return collected


def _load_presets(path, collected, seen):
    path = path.resolve()
    if path in seen:
        return
    seen.add(path)
    try:
        data = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as exc:
        raise ForgeError(f"Cannot read CMake presets {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ForgeError(f"CMake presets must be a JSON object: {path}")
    includes = data.get("include") or []
    if isinstance(includes, str):
        includes = [includes]
    if not isinstance(includes, list):
        raise ForgeError(f"CMake preset include must be a list: {path}")
    for item in includes:
        if not isinstance(item, str) or not item:
            raise ForgeError(f"CMake preset include must be a path: {path}")
        included = Path(item)
        if not included.is_absolute():
            included = path.parent / included
        if not included.is_file():
            raise ForgeError(f"CMake preset include not found: {included}")
        _load_presets(included, collected, seen)
    presets = data.get("configurePresets") or []
    if not isinstance(presets, list):
        raise ForgeError(f"configurePresets must be a list: {path}")
    for preset in presets:
        if not isinstance(preset, dict) or not isinstance(preset.get("name"), str) or not preset["name"]:
            raise ForgeError(f"CMake configure preset in {path} has no name.")
        preset_name = preset["name"]
        if preset_name in collected:
            raise ForgeError(f"Duplicate CMake configure preset: {preset_name}")
        collected[preset_name] = {**preset, "_file_dir": str(path.parent)}


def _resolve_preset(presets, name, stack):
    if name in stack:
        raise ForgeError("Cyclic CMake preset inheritance: " + " -> ".join([*stack, name]))
    item = presets[name]
    inherits = item.get("inherits") or []
    if isinstance(inherits, str):
        inherits = [inherits]
    if not isinstance(inherits, list) or not all(isinstance(parent, str) for parent in inherits):
        raise ForgeError(f"CMake preset {name} has an invalid inherits value.")
    merged = {}
    for parent in inherits:
        if parent not in presets:
            raise ForgeError(f"CMake preset {name} inherits unknown preset {parent}.")
        parent_values = _resolve_preset(presets, parent, stack + [name])
        for key, value in parent_values.items():
            if key == "_file_dir":
                continue
            if key == "cacheVariables" and isinstance(merged.get(key), dict) and isinstance(value, dict):
                merged[key] = {**merged[key], **value}
            else:
                merged[key] = value
        if "binaryDir" in parent_values and "_file_dir" in parent_values:
            merged["_file_dir"] = parent_values["_file_dir"]
    for key, value in item.items():
        if key == "_file_dir":
            if "binaryDir" in item:
                merged["_file_dir"] = value
            continue
        if key == "cacheVariables" and isinstance(merged.get(key), dict) and isinstance(value, dict):
            merged[key] = {**merged[key], **value}
        else:
            merged[key] = value
    return merged


def _expand_preset_path(value, *, source, preset, file_dir, generator):
    host = {"linux": "Linux", "darwin": "Darwin", "win32": "Windows"}.get(sys.platform, sys.platform)
    mapping = {"sourceDir": str(source), "sourceParentDir": str(source.parent), "sourceDirName": source.name,
               "presetName": preset, "generator": generator, "hostSystemName": host, "fileDir": str(file_dir)}

    def replace(match):
        if match.group(1):
            key = match.group(1)
            if key not in mapping:
                raise ForgeError(f"Unsupported CMake preset macro ${{{key}}} in binaryDir.")
            return mapping[key]
        if match.group(2):
            if match.group(2) not in os.environ:
                raise ForgeError(f"CMake preset environment variable is unset: {match.group(2)}")
            return os.environ[match.group(2)]
        return os.environ.get(match.group(3), "")

    current = value
    for _ in range(8):
        updated = _PRESET_MACRO.sub(replace, current)
        if updated == current:
            break
        current = updated
    if "${" in current or "$env{" in current or "$penv{" in current:
        raise ForgeError(f"Unresolved CMake preset binaryDir: {value}")
    return current
