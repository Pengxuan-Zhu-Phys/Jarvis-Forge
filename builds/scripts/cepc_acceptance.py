"""Run the CEPC handoff validators against the Forge-installed generators."""

import argparse
import hashlib
import json
import os
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path


INPUTS = (
    "versions.json", "report_back_template.json", "validate_whizard.py", "validate_mg5.py",
    "cards/whizard/ww_240.sin", "cards/whizard/ww4f_240.sin", "cards/whizard/ww4f_240_isr.sin",
    "cards/madgraph/ww_born_240.mg5", "cards/madgraph/export_standalone.mg5",
    "reference/born_240.json", "reference/whizard_240_local.json",
)


def setup_inputs(directory):
    setup = directory / "server_setup"
    manifest = setup / "SHA256SUMS"
    if not manifest.is_file():
        raise ValueError(f"Copy the CEPC server_setup handoff into {setup} before building.")
    entries = (line.split(maxsplit=1) for line in manifest.read_text().splitlines() if line.strip())
    expected = {path: digest for digest, path in entries}
    inputs = {}
    for name in INPUTS:
        source = setup / name
        if not source.resolve().is_relative_to(setup.resolve()) or not source.is_file():
            raise ValueError(f"Missing CEPC handoff input: {source}")
        content = source.read_bytes()
        if hashlib.sha256(content).hexdigest() != expected.get(name):
            raise ValueError(f"CEPC handoff checksum mismatch: {source}")
        inputs[name] = content
    return inputs


def run(argv, directory, log):
    print(shlex.join(str(arg) for arg in argv), flush=True)
    with log.open("w") as stream:
        subprocess.run(argv, cwd=directory, stdin=subprocess.DEVNULL,
                       stdout=stream, stderr=subprocess.STDOUT, check=True)


def write_environment(path, variables, bins, tool_bins, libraries):
    # Keep the invoking shell's pyenv selection. Only add the native tool paths.
    paths = [shlex.quote(":".join(map(str, dict.fromkeys(items))))
             for items in (bins, tool_bins, libraries)]
    bin_path, tool_path, library_path = paths
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write("# Generated by CEPC-build. Source this from Bash.\n")
        for name, value in variables.items():
            stream.write(f"export {name}={shlex.quote(str(value))}\n")
        stream.write(f'export PATH={bin_path}${{PATH:+:$PATH}}:{tool_path}\n')
        stream.write(f'export LD_LIBRARY_PATH={library_path}${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}\n')
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def accept(args, inputs):
    run_dir = Path(tempfile.mkdtemp(prefix="acceptance-", dir=args.work))
    print(f"CEPC acceptance logs and report: {run_dir}", flush=True)
    setup = run_dir / "server_setup"
    for name, content in inputs.items():
        target = setup / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)

    report = json.loads(inputs["report_back_template.json"])
    versions = json.loads(inputs["versions.json"])
    report_path = run_dir / "report.json"
    environment = args.workspace / "env.sh"
    whizard = args.whizard / "bin/whizard"
    card = args.workspace / "build.yaml"
    if not card.is_file():
        card = args.workspace / "CEPC-build.yaml"
    report.update(
        host_os_arch=platform.platform(),
        host_distribution=platform.freedesktop_os_release().get("PRETTY_NAME"),
        cpu_count=os.cpu_count(),
        memory_bytes=os.sysconf("SC_PAGE_SIZE") * os.sysconf("SC_PHYS_PAGES"),
        python_version=platform.python_version(),
        python_executable=sys.executable,
        install_prefixes={"whizard": str(args.whizard), "madgraph": str(args.madgraph),
                          "ocaml": str(args.ocaml)},
        source_archive_sha256={name: versions[name]["sha256"] for name in ("whizard", "madgraph")},
        input_sha256={name: hashlib.sha256(content).hexdigest() for name, content in inputs.items()},
        reproduction_commands=[shlex.join(["jforge", "build", "run", str(card)])],
        optional_components={"ROOT/Delphes": "outside the parton-level baseline"},
    )
    try:
        build = json.loads((args.whizard / "share/cepc-whizard-build.json").read_text())
        if build["make_check"] != "passed":
            raise ValueError("WHIZARD upstream make check has no passing record.")
        log = next(iter(sorted((args.whizard / ".spack").glob("spack-build-out.txt*"))), None)
        if log is None:
            raise ValueError("WHIZARD is missing its archived Spack build log.")
        compilers = build["compiler"]
        report.update(
            whizard_configure_flags=build["configure_args"],
            whizard_make_check_log=str(log),
            compiler_versions={key: subprocess.check_output([exe, "--version"], text=True).splitlines()[0]
                               for key, exe in compilers.items() if key != "F77"},
            ocaml_version=subprocess.check_output([args.ocaml / "bin/ocamlc", "-version"], text=True).strip(),
        )
        mg5_version = re.search(r"^version\s*=\s*(\S+)", (args.madgraph / "VERSION").read_text(), re.M)
        if not mg5_version or mg5_version[1] != "3.8.1":
            raise ValueError("The CEPC baseline requires MadGraph 3.8.1.")
        report["mg5_version"] = mg5_version[1]
        os.environ.update(compilers, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1")

        whizard_json = run_dir / "whizard.json"
        whizard_command = [sys.executable, setup / "validate_whizard.py", "--run", "--whizard", whizard,
                           "--runs-dir", run_dir / "whizard", "--output", whizard_json]
        run(whizard_command, run_dir, run_dir / "whizard.log")
        whizard_result = json.loads(whizard_json.read_text())
        report.update(whizard_version=whizard_result["version_output"], whizard_acceptance_json=str(whizard_json))

        # MG5 writes configuration and process files during execution.
        mg5 = run_dir / "mg5"
        shutil.copytree(args.madgraph, mg5, ignore=shutil.ignore_patterns(".spack"))
        with (mg5 / "input/mg5_configuration.txt").open("a") as config:
            config.write(f"\ncpp_compiler = {compilers['CXX']}\nfortran_compiler = {compilers['FC']}\n")
        frontend = [sys.executable, mg5 / "bin/mg5_aMC"]
        born_card = setup / "cards/madgraph/ww_born_240.mg5"
        export_card = setup / "cards/madgraph/export_standalone.mg5"
        born_work = run_dir / "mg5-born"
        born_work.mkdir()
        born = born_work / "ww_born_240"
        mg5_json = run_dir / "mg5-born.json"
        mg5_check = [sys.executable, setup / "validate_mg5.py", "--process-dir", born, "--output", mg5_json]
        run([*frontend, born_card], born_work, run_dir / "mg5-born.log")
        run(mg5_check, run_dir, run_dir / "mg5-check.log")
        measured = json.loads(mg5_json.read_text())
        report.update(
            mg5_born_cross_section_pb=measured["cross_section_pb"],
            mg5_born_integration_error_pb=measured["error_pb"],
            mg5_card_and_event_paths=[str(born / name) for name in measured["sha256"]],
        )

        export_work = run_dir / "mg5-standalone"
        export_work.mkdir()
        run([*frontend, export_card], export_work, run_dir / "mg5-export.log")
        for name in ("wwprod", "ww4f_cc03"):
            output = export_work / name
            if (not all((output / "src" / source).is_file() for source in ("HelAmps_sm.cc", "Parameters_sm.cc"))
                    or not list((output / "SubProcesses").glob("P*/*.cc"))):
                raise ValueError(f"Incomplete MG5 standalone C++ export: {output}")
        report["mg5_standalone_export_status"] = "passed"

        bin_dirs = [args.whizard / "bin", args.madgraph / "bin", args.ocaml / "bin"]
        tool_bins = []
        for tool in ("make", "perl", "bash"):
            executable = shutil.which(tool)
            if executable is None:
                raise ValueError(f"Required runtime tool missing: {tool}")
            tool_bins.append(Path(executable).parent)
        tool_bins.extend(Path(executable).parent for executable in compilers.values())
        write_environment(environment, {
            **compilers, "WHIZARD_PREFIX": args.whizard, "MG5_ROOT": args.madgraph,
            "CEPC_TOOLS": args.workspace, "CEPC_RUNS": args.workspace / "cepc-runs",
            "OMP_NUM_THREADS": 1, "OPENBLAS_NUM_THREADS": 1, "MKL_NUM_THREADS": 1,
        }, bin_dirs, tool_bins, [args.whizard / "lib"])
        report.update(status="passed", environment_entrypoint=str(environment))
        print(f"CEPC 240 GeV acceptance passed. Source {environment}", flush=True)
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        report.update(status="failed", known_failures_or_unverified_items=[str(exc)])
        raise
    finally:
        report_path.write_text(json.dumps(report, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="mode", required=True)
    preflight = commands.add_parser("preflight")
    preflight.add_argument("workspace", type=Path)
    validate = commands.add_parser("validate")
    for name in ("workspace", "work", "whizard", "madgraph", "ocaml"):
        validate.add_argument(name, type=Path)
    args = parser.parse_args()
    try:
        inputs = setup_inputs(args.workspace)
        if args.mode == "preflight":
            print("CEPC handoff checksums verified.")
        else:
            accept(args, inputs)
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        raise SystemExit(f"CEPC-build: {exc}") from exc


if __name__ == "__main__":
    main()
