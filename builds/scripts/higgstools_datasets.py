def _portable(value, depth=0):
    if depth > 64:
        raise RuntimeError("Dataset JSON nesting exceeds 64 levels")
    if value is None or type(value) in (str, bool, int):
        return value
    if type(value) is float and value == value and abs(value) != float("inf"):
        return value
    if isinstance(value, list):
        return [_portable(item, depth + 1) for item in value]
    if isinstance(value, dict) and all(type(key) is str for key in value):
        return {key: _portable(item, depth + 1) for key, item in value.items()}
    raise RuntimeError("Dataset JSON contains a value that cannot be fingerprinted")


def fingerprint(value):
    raw = json.dumps(_portable(value), sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return "sha256:" + hashlib.sha256(raw.encode()).hexdigest()


def inspect_tree(root):
    """sha256-json-tree-v1 over the sorted JSON files in one dataset root."""
    files = sorted(Path(root).rglob("*.json"))
    tree = []
    for file in files:
        if not file.resolve().is_relative_to(Path(root).resolve()):
            raise RuntimeError("Dataset JSON symlink escapes its directory: " + str(file))
        document = json.loads(file.read_text(encoding="utf-8"))
        tree.append([file.relative_to(root).as_posix(), fingerprint(document)])
    if not tree:
        raise RuntimeError("Dataset has no JSON entries: " + str(root))
    return {"fingerprint": fingerprint(tree), "json_count": len(files)}


def relative_dataset(entry):
    digest = entry["fingerprint"].split(":", 1)[1]
    return f"datasets/{entry['kind']}/{entry['version']}/{digest}"


def activation_script():
    """Shell script installed at share/HiggsTools/datasets.sh."""
    lines = [
        "# Generated by higgstools-build. Sourced by the HiggsTools activation.",
        '_jforge_hts_root=$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/datasets',
        f'export {CACHE_ENV}="$_jforge_hts_root"',
    ]
    for entry in DATASETS:
        digest = entry["fingerprint"].split(":", 1)[1]
        path = f'"$_jforge_hts_root/{entry["kind"]}/{entry["version"]}/{digest}"'
        lines.append(f"export {entry['names'][0]}={path}")
        lines.append(f"export {entry['names'][1]}=\"${entry['names'][0]}\"")
    lines.append("unset _jforge_hts_root")
    return "\n".join(lines) + "\n"


def cache_root(prefix):
    return Path(prefix) / "share" / "HiggsTools" / "datasets"


def dataset_path(prefix, entry):
    return cache_root(prefix) / entry["kind"] / entry["version"] / entry["fingerprint"].split(":", 1)[1]


class _HTTPSRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if not str(newurl).startswith("https://"):
            raise RuntimeError("Dataset download refused a non-HTTPS redirect")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _download(entry, output):
    if not entry["url"].startswith("https://"):
        raise RuntimeError("Dataset URL must use HTTPS")
    opener = urllib.request.build_opener(_HTTPSRedirect())
    started = time.monotonic()
    with opener.open(entry["url"], timeout=60) as response, output.open("wb") as handle:
        total = 0
        while True:
            chunk = response.read(1024 * 1024)
            if not chunk:
                break
            total += len(chunk)
            if total > entry["max_archive_bytes"] or time.monotonic() - started > 300:
                raise RuntimeError(f"{entry['kind']} download exceeded its size or time limit")
            handle.write(chunk)


def _extract(archive, destination):
    total = 0
    count = 0
    roots = set()
    with tarfile.open(archive) as tar:
        for member in tar:
            path = PurePosixPath(member.name)
            if path.is_absolute() or ".." in path.parts or not path.parts:
                raise RuntimeError("Dataset archive contains an unsafe path")
            if not member.isfile() and not member.isdir():
                raise RuntimeError("Dataset archive contains a link or special file")
            roots.add(path.parts[0])
            total += member.size
            count += 1
            if total > 512 * 1024 * 1024 or count > 20000:
                raise RuntimeError("Dataset archive exceeds the extraction limit")
            target = destination / path
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            extracted = tar.extractfile(member)
            if extracted is None:
                raise RuntimeError("Dataset archive entry has no content: " + member.name)
            with extracted, target.open("wb") as output:
                shutil.copyfileobj(extracted, output)
    if len(roots) != 1:
        raise RuntimeError("Dataset archive must contain one root directory")
    return destination / next(iter(roots))


def install_entry(prefix, entry, archive=None):
    """Install one pinned dataset. Return its directory."""
    target = dataset_path(prefix, entry)
    if target.is_dir():
        inspected = inspect_tree(target)
        if inspected["fingerprint"] != entry["fingerprint"] or inspected["json_count"] != entry["json_count"]:
            raise RuntimeError(f"Installed {entry['kind']} does not match the pinned tree: {target}")
        print(f"{entry['kind']} {entry['version']} already installed", flush=True)
        return target
    parent = target.parent
    parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".staging-", dir=parent) as temporary:
        staging = Path(temporary)
        archive_path = Path(archive) if archive else staging / "download.tar.gz"
        if archive is None:
            _download(entry, archive_path)
        digest = hashlib.sha256(archive_path.read_bytes()).hexdigest()
        if archive_path.stat().st_size > entry["max_archive_bytes"] or digest != entry["sha256"]:
            raise RuntimeError(f"{entry['kind']} archive SHA-256 mismatch")
        dataset = _extract(archive_path, staging / "unpacked")
        inspected = inspect_tree(dataset)
        if inspected["fingerprint"] != entry["fingerprint"] or inspected["json_count"] != entry["json_count"]:
            raise RuntimeError(
                f"{entry['kind']} JSON tree does not match the pin: "
                f"{inspected['fingerprint']} ({inspected['json_count']} files)"
            )
        manifest = dict(entry)
        (dataset / ".hts-resource-manifest").write_text(json.dumps(manifest, sort_keys=True), encoding="utf-8")
        version_file = dataset / "VERSION"
        if not version_file.exists():
            version_file.write_text(entry["version"] + "\n", encoding="utf-8")
        os.rename(dataset, target)
    print(f"installed {entry['kind']} {entry['version']}", flush=True)
    return target


def python_environment_line(prefix):
    root = cache_root(prefix).resolve()
    values = {CACHE_ENV: str(root)}
    for entry in DATASETS:
        path = str(dataset_path(prefix, entry).resolve())
        values[entry["names"][0]] = path
    parts = ["import os"]
    for name in (CACHE_ENV, DATASETS[0]["names"][0], DATASETS[1]["names"][0]):
        parts.append(f"os.environ.setdefault({json.dumps(name)}, {json.dumps(values[name])})")
    for entry in DATASETS:
        canonical = entry["names"][0]
        legacy = entry["names"][1]
        parts.append(
            f"os.environ.setdefault({json.dumps(legacy)}, os.environ[{json.dumps(canonical)}])"
        )
    return "; ".join(parts) + "\n"


def install_python_environment(prefix, site_packages=None):
    site = Path(site_packages) if site_packages is not None else Path(sysconfig.get_path("purelib"))
    if not site.is_dir():
        raise RuntimeError("Python site-packages is missing: " + str(site))
    destination = site / "higgstools-datasets.pth"
    destination.write_text(python_environment_line(prefix), encoding="utf-8")
    print("configured " + str(destination), flush=True)
    return destination


def probe_native(prefix):
    os.environ.pop("PYTHONPATH", None)
    import Higgs
    bounds = dataset_path(prefix, DATASETS[0])
    signals = dataset_path(prefix, DATASETS[1])
    Higgs.Bounds(str(bounds))
    Higgs.Signals(str(signals))
    print(json.dumps({
        "hb": str(bounds),
        "hs": str(signals),
        "hb_version": DATASETS[0]["version"],
        "hs_version": DATASETS[1]["version"],
        "cache": str(cache_root(prefix).resolve()),
    }), flush=True)


def install_datasets(prefix, archives=None, site_packages=None, probe=False):
    prefix = Path(prefix)
    archives = archives or {}
    installed = []
    for entry in DATASETS:
        installed.append(install_entry(prefix, entry, archive=archives.get(entry["kind"])))
    script = prefix / "share" / "HiggsTools" / "datasets.sh"
    if not script.is_file() or script.read_text(encoding="utf-8") != activation_script():
        raise RuntimeError("HiggsTools activation script is missing: " + str(script))
    pth = install_python_environment(prefix, site_packages=site_packages)
    if probe:
        probe_native(prefix)
    return {"datasets": [str(path) for path in installed], "python_environment": str(pth)}


def main(argv):
    if len(argv) != 2:
        raise SystemExit("usage: higgstools_datasets.py PREFIX")
    install_datasets(argv[1], probe=True)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main(sys.argv))
    except Exception as exc:
        raise SystemExit(str(exc)) from exc
